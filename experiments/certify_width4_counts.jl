function width4_count_common_polynomial(recurrences)
    first_coefficients = parse.(BigInt, recurrences[1]["coefficients"])
    stripped = count_recurrence_integer_factors(first_coefficients)
    root = count_monic_polynomial_root(stripped.remainder, 2)
    common = count_polynomial_product(BigInt[1, -3, 2], root)
    for (recurrence, exponent) in zip(recurrences, (2, 4, 3))
        expected = count_polynomial_product(BigInt[1, -4, 4], count_polynomial_power(common, exponent))
        actual = vcat(big(1), -parse.(BigInt, recurrence["coefficients"]))
        expected == actual || error("the common-polynomial factorization failed")
        recurrence["common_polynomial_exponent"] = exponent
    end
    return common
end

function certify_width4_counts(path = joinpath(@__DIR__, "results", "width4_count_recurrences.toml"))
    audit = Width4SemanticCertificate.load_semantic_certificate()
    language = width4_optimal_language(audit)
    quotient = width4_optimal_count_quotient(language)
    recurrences = Dict{String, Any}[]
    for offset in 0:2
        coefficients = propose_count_recurrence(quotient; offset = offset)
        certify_count_recurrence(quotient, coefficients; offset = offset) ||
            error("candidate counting recurrence failed exact certification")
        initial = quotient_residue_counts(quotient, length(coefficients) - 1; offset = offset)
        factorization = count_recurrence_integer_factors(coefficients)
        push!(recurrences, Dict(
            "first_width" => 19 + offset,
            "width_step" => 3,
            "order" => length(coefficients),
            "coefficients" => string.(coefficients),
            "initial_counts" => string.(initial),
            "integer_roots" => first.(factorization.integer_factors),
            "root_multiplicities" => last.(factorization.integer_factors),
            "remaining_polynomial" => string.(factorization.remainder),
        ))
        println((first_width = 19 + offset, order = length(coefficients), verified = true))
    end
    common = width4_count_common_polynomial(recurrences)
    println("common polynomial (descending coefficients) = ", common)
    report = Dict(
        "optimal_language_states" => length(language.ids),
        "optimal_language_edges" => length(language.edges),
        "counting_quotient_states" => length(quotient.accepting),
        "counting_quotient_edges" => length(quotient.edges),
        "exact_residuals_checked_per_recurrence" => length(quotient.accepting),
        "common_polynomial" => string.(common),
        "recurrences" => recurrences,
    )
    open(path, "w") do io
        println(io, "# Generated by julia experiments/certify_width4_counts.jl.")
        println(io, "# a[k+d] = sum(coefficients[i] * a[k+d-i], i=1:d), k >= 0.")
        println(io, "# a[k] counts maximizing seed sets at first_width + 3*k.")
        println(io, "# Integers are strings where needed to preserve arbitrary precision.")
        TOML.print(io, report; sorted = true)
    end
    return report
end

if abspath(PROGRAM_FILE) == @__FILE__
    certify_width4_counts(isempty(ARGS) ? joinpath(@__DIR__, "results", "width4_count_recurrences.toml") : ARGS[1])
end

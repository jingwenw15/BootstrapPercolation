using SHA

if !@isdefined(Width4SemanticCertificate)
    include("check_width4_semantic_certificate.jl")
end

function paper_follow_columns!(audit, columns; state = nothing, processed = 0)
    checker = Width4SemanticCertificate
    if state === nothing
        state = (0, 0, checker.intern!(audit.context, BitSet([0])), ())
    end
    for column in columns
        state = checker.semantic_transition!(audit.context, state, column, min(processed, 2))
        state === nothing && error("the paper construction has a rejected prefix")
        processed += 1
    end
    return state
end

function paper_construction_certificate!(audit)
    checker = Width4SemanticCertificate
    block = [1, 1, 0]
    suffix = [2, 10, 8, 0, 1, 5, 4]
    specs = (
        (residue = 0, left = [2, 0], base_cols = 9),
        (residue = 1, left = Int[], base_cols = 10),
        (residue = 2, left = [2, 0, 1, 0], base_cols = 11),
    )
    loops = NamedTuple[]

    for spec in specs
        prefix = vcat(spec.left, block)
        first = paper_follow_columns!(audit, prefix)
        second = paper_follow_columns!(audit, block; state = first, processed = length(prefix))
        second == first || error("the paper's repeating block does not close")
        terminal = paper_follow_columns!(audit, suffix; state = first, processed = length(prefix))
        checker.semantic_accepting(audit.context, terminal) || error("construction suffix is not accepting")

        copies = div(spec.base_cols - length(spec.left) - length(suffix), length(block))
        base_columns = vcat(spec.left, repeat(block, copies), suffix)
        length(base_columns) == spec.base_cols || error("construction length mismatch")
        base_state = paper_follow_columns!(audit, base_columns)
        checker.semantic_accepting(audit.context, base_state) || error("construction base is not accepting")
        base_size = sum(count_ones, base_columns)
        base_size == fld(2 * spec.base_cols + 10, 3) || error("construction size mismatch")
        push!(loops, (
            residue = spec.residue,
            base_cols = spec.base_cols,
            base_size = base_size,
            returns_to_same_state = second == first,
            suffix_accepts = true,
            base_accepts = true,
        ))
    end
    return (block_length = length(block), block_weight = sum(count_ones, block), loops = loops)
end

function write_paper_results(path = joinpath(@__DIR__, "..", "paper", "verified_results.md"))
    root = dirname(@__DIR__)
    audit = Width4SemanticCertificate.load_semantic_certificate()
    result = Width4SemanticCertificate.verify_loaded_semantic_certificate!(audit)
    construction = paper_construction_certificate!(audit)
    inputs = (
        "experiments/results/width4_interior_graph_states.csv",
        "experiments/results/width4_interior_graph_transitions.csv",
        "experiments/results/width4_boundary_certificate_vertices.csv",
        "experiments/results/width4_boundary_certificate_edges.csv",
    )

    open(path, "w") do io
        println(io, "# Verified Manuscript Data\n")
        println(io, "Generated by `julia experiments/prepare_paper.jl` after the complete independent semantic and arithmetic audit.\n")
        println(io, "Julia version: `", VERSION, "`. No random choices are used.\n")
        println(io, "## Certificate Summary\n")
        println(io, "| Quantity | Verified value |\n|---|---:|")
        for (label, value) in (
            ("Semantic states", result.states),
            ("Labeled edges", result.edges),
            ("Column choices checked", result.column_choices_checked),
            ("Warm-up states", result.warmup_states),
            ("Accepting states", result.accepting_states),
            ("Boundary-core states", result.arithmetic.core_states),
            ("Boundary-core edges", result.arithmetic.core_edges),
            ("Recurrence start", result.arithmetic.recurrence_start),
            ("Recurrence verification column", result.arithmetic.recurrence_end),
            ("Period", result.arithmetic.period),
            ("Gain", result.arithmetic.gain),
        )
            println(io, "| ", label, " | ", value, " |")
        end
        println(io, "\n## Exact Finite Prefix\n")
        println(io, "| n | E(4,n), computed from the verified graph |\n|---:|---:|")
        for n in 4:result.arithmetic.recurrence_end
            println(io, "| ", n, " | ", result.arithmetic.values[n], " |")
        end
        println(io, "\n## Independently Checked Construction Loops\n")
        println(io, "Block length: ", construction.block_length, "; seed gain: ", construction.block_weight, ".\n")
        println(io, "| n mod 3 | Base length | Base size | Same state after another block | Suffix accepts | Base accepts |")
        println(io, "|---:|---:|---:|---|---|---|")
        for loop in construction.loops
            println(io, "| ", loop.residue, " | ", loop.base_cols, " | ", loop.base_size,
                " | ", loop.returns_to_same_state, " | ", loop.suffix_accepts, " | ", loop.base_accepts, " |")
        end
        println(io, "\n## Certificate Input Digests\n")
        println(io, "SHA-256 binds this report to the exact certificate files checked. The digests are computed after verification; they are not substitutes for verification.\n")
        for input in inputs
            digest = open(SHA.sha256, joinpath(root, input))
            println(io, "- `", input, "`: `", bytes2hex(digest), "`")
        end
    end
    return (path = abspath(path), result = result, construction = construction)
end

if abspath(PROGRAM_FILE) == @__FILE__
    path = isempty(ARGS) ? joinpath(@__DIR__, "..", "paper", "verified_results.md") : ARGS[1]
    result = write_paper_results(path)
    println("verified manuscript data = ", result.path)
    println("independent construction loops = ", length(result.construction.loops))
end
